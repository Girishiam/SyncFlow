-- V3: every notification belongs to exactly one user, and audit-chain verification is incremental.

-- 1. Fan out legacy role-targeted notifications into one row per active member of that role,
--    so marking one as read no longer marks it read for everybody.
INSERT INTO notifications (is_read, created_at, read_at, reference_id, target_role_id, recipient_id, priority,
                           sender_avatar, action_type, type, sender_name, link_url, message, title)
SELECT n.is_read, n.created_at, n.read_at, n.reference_id, NULL, u.id, n.priority,
       n.sender_avatar, n.action_type, n.type, n.sender_name, n.link_url, n.message, n.title
FROM notifications n
JOIN users u ON u.role_id = n.target_role_id AND u.status = 'ACTIVE'
WHERE n.recipient_id IS NULL AND n.target_role_id IS NOT NULL;

-- 2. Fan out legacy system-wide notifications (no recipient, no role) to every active user.
INSERT INTO notifications (is_read, created_at, read_at, reference_id, target_role_id, recipient_id, priority,
                           sender_avatar, action_type, type, sender_name, link_url, message, title)
SELECT n.is_read, n.created_at, n.read_at, n.reference_id, NULL, u.id, n.priority,
       n.sender_avatar, n.action_type, n.type, n.sender_name, n.link_url, n.message, n.title
FROM notifications n
CROSS JOIN users u
WHERE n.recipient_id IS NULL AND n.target_role_id IS NULL AND u.status = 'ACTIVE';

DELETE FROM notifications WHERE recipient_id IS NULL;
GO

-- 3. Drop the role targeting column (its FK name was generated by Hibernate, so look it up).
DECLARE @fk nvarchar(256);
SELECT @fk = fk.name
FROM sys.foreign_keys fk
JOIN sys.foreign_key_columns fkc ON fkc.constraint_object_id = fk.object_id
JOIN sys.columns c ON c.object_id = fkc.parent_object_id AND c.column_id = fkc.parent_column_id
WHERE fk.parent_object_id = OBJECT_ID('notifications') AND c.name = 'target_role_id';
IF @fk IS NOT NULL EXEC('ALTER TABLE notifications DROP CONSTRAINT ' + @fk);
GO
ALTER TABLE notifications DROP COLUMN target_role_id;
GO

-- 4. Recipient is now mandatory (the index must be dropped to change nullability).
DROP INDEX IX_notifications_recipient ON notifications;
ALTER TABLE notifications ALTER COLUMN recipient_id uniqueidentifier NOT NULL;
CREATE INDEX IX_notifications_recipient ON notifications (recipient_id, is_read);
CREATE INDEX IX_notifications_dedupe ON notifications (reference_id, type, recipient_id, created_at);
GO

-- 5. Audit chain verification checkpoint: metrics verify only records added since the last check;
--    a full re-verification runs nightly and on demand.
CREATE TABLE audit_chain_checkpoint (
    id                    int NOT NULL PRIMARY KEY,
    last_verified_id      bigint NOT NULL,
    last_hash             varchar(64) NULL,
    verified_records      bigint NOT NULL,
    legacy_records        bigint NOT NULL,
    broken_records        bigint NOT NULL,
    first_broken_id       bigint NULL,
    last_full_check_at    datetimeoffset(6) NULL,
    updated_at            datetimeoffset(6) NOT NULL
);
GO
